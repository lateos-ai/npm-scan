import path from 'path';
import thresholds from './config/thresholds.js';

const cfg = thresholds['D23-GITHUB-AUTHOR-SPOOF'];
const PATTERN_WEIGHTS = cfg.pattern_weights;

const CODE_EXTENSIONS = new Set([
  '.js', '.mjs', '.cjs', '.ts',
]);

function isCodeFile(f) {
  const fp = (f.path || f.name || '').toLowerCase();
  return CODE_EXTENSIONS.has(path.extname(fp));
}

function concatSources(jsFiles, allFiles) {
  const files = allFiles || jsFiles || [];
  const sources = [];
  for (const f of files) {
    if (f.content && isCodeFile(f)) sources.push(f.content);
  }
  return sources.join('\n');
}

function extractLines(content, matchIndex) {
  if (!content) return 1;
  const before = content.slice(0, matchIndex);
  return (before.match(/\n/g) || []).length + 1;
}

function matchAllSafe(regex, str) {
  const flags = regex.flags.includes('g') ? regex.flags : regex.flags + 'g';
  const fresh = new RegExp(regex.source, flags);
  const results = [];
  let m;
  while ((m = fresh.exec(str)) !== null) {
    results.push(m);
    if (m.index === fresh.lastIndex) fresh.lastIndex++;
  }
  return results;
}

export const name = 'tier1-github-author-spoof';

export function scan(pkgJson, jsFiles, registryMeta, allFiles) {
  const files = allFiles || jsFiles || [];
  if (files.length === 0) return [];

  const source = concatSources(jsFiles, allFiles);
  if (!source) return [];

  const findings = [];
  let aggregatedRisk = 0;
  const seen = new Set();

  function tryAdd(type, patterns) {
    if (seen.has(type)) return;
    const weight = PATTERN_WEIGHTS[type];
    for (const regex of patterns) {
      for (const match of matchAllSafe(regex, source)) {
        seen.add(type);
        findings.push({
          detector: 'tier1-github-author-spoof',
          id: 'D23-GITHUB-AUTHOR-SPOOF',
          severity: weight >= 85 ? 'high' : 'medium',
          confidence: weight >= 90 ? 'HIGH' : 'MEDIUM',
          confidenceScore: weight,
          message: `${type.replace(/_/g, ' ')} detected`,
          evidence: [`pattern: ${type}`, `match: ${match[0].slice(0, 120)}`],
          locations: [{ file: 'install.js', line: extractLines(source, match.index) }],
        });
        aggregatedRisk += weight;
        return;
      }
    }
  }

  tryAdd('github_author_spoof', [
    /"claude@users\.noreply\.github\.com"/gi,
    /'claude@users\.noreply\.github\.com'/gi,
    /"gpt@users\.noreply\.github\.com"/gi,
    /"openai@users\.noreply\.github\.com"/gi,
    /"anthropic@users\.noreply\.github\.com"/gi,
    /"cursorde@users\.noreply\.github\.com"/gi,
    /"gemini@users\.noreply\.github\.com"/gi,
  ]);

  tryAdd('spoofed_git_commit', [
    /git\s+config\s+user\.email.*noreply\.github\.com/gi,
    /git\s+commit.*--author.*noreply\.github\.com/gi,
    /--author="claude@users\.noreply\.github\.com"/gi,
    /--author="gpt@users\.noreply\.github\.com"/gi,
  ]);

  tryAdd('force_push', [
    /git\s+push.*--force(?!-with-lease)/gi,
    /git\s+push.*-f\s+/gi,
  ]);

  tryAdd('force_push_lease', [
    /git\s+push.*--force-with-lease/gi,
  ]);

  tryAdd('ai_workflow_impersonation', [
    /["']Automated PR|AI-generated|Generated by Claude|OpenAI-assisted|Cursor-assisted|Gemini-generated["']/i,
    /["']feat: AI-powered|chore: automated by Claude|docs: generated by OpenAI["']/i,
    /["']This PR was created automatically/i,
  ]);

  tryAdd('full_author_spoof_attack', [
    /--author="claude@users\.noreply\.github\.com".*--force/gi,
    /git\s+config.*claude@users\.noreply.*git\s+push.*--force/gi,
    /"claude@users\.noreply\.github\.com".*"AI-generated|Automated PR"/gi,
  ]);

  tryAdd('authenticated_spoof_push', [
    /process\.env\.GITHUB_TOKEN.*git\s+commit.*git\s+push/gi,
    /github_token.*--author.*noreply.*push.*--force/gi,
  ]);

  tryAdd('repo_hijacking', [
    /git\s+config.*user\.email.*noreply\.github\.com/gi,
    /git\s+config.*user\.name.*claude|gpt|openai|anthropic|cursorde|gemini/gi,
    /"author":\s*"claude@users\.noreply\.github\.com"/gi,
  ]);

  if (findings.length === 0) return [];

  const overallScore = Math.min(100, Math.max(0, aggregatedRisk));
  let severity;
  if (overallScore >= cfg.flag_threshold) {
    severity = 'critical';
  } else if (overallScore >= cfg.warn_threshold) {
    severity = 'high';
  } else if (overallScore >= 30) {
    severity = 'medium';
  } else {
    severity = 'low';
  }

  function confidenceLabel(sc) {
    if (sc >= 80) return 'HIGH';
    if (sc >= 50) return 'MEDIUM';
    return 'LOW';
  }

  const hasSpoof = findings.some((f) =>
    f.evidence?.some((e) => e.includes('github_author_spoof'))
  );
  const hasFullAttack = findings.some((f) =>
    f.evidence?.some((e) => e.includes('full_author_spoof_attack'))
  );
  const hasAuthPush = findings.some((f) =>
    f.evidence?.some((e) => e.includes('authenticated_spoof_push'))
  );
  const hasSpoofedCommit = findings.some((f) =>
    f.evidence?.some((e) => e.includes('spoofed_git_commit'))
  );

  let recommendation = 'PASS';
  if (hasFullAttack) {
    recommendation = 'BLOCK - Complete author spoofing attack sequence detected';
  } else if (hasAuthPush) {
    recommendation = 'BLOCK - Authenticated spoofed commit push detected';
  } else if (hasSpoof && hasSpoofedCommit) {
    recommendation = 'BLOCK - GitHub author spoofing with commit forgery detected';
  } else if (hasSpoof) {
    recommendation = 'BLOCK - GitHub author spoofing detected';
  } else if (overallScore >= cfg.warn_threshold) {
    recommendation = 'WARN - Suspicious git operations detected';
  }

  return [
    {
      detector: 'tier1-github-author-spoof',
      id: 'D23-GITHUB-AUTHOR-SPOOF',
      severity,
      confidence: confidenceLabel(overallScore),
      confidenceScore: overallScore,
      message: `GitHub Author Spoof detected (aggregated risk: ${aggregatedRisk})`,
      evidence: [
        `total_findings: ${findings.length}`,
        `aggregated_risk: ${aggregatedRisk}`,
        ...findings.map((f) => {
          const loc = f.locations?.[0];
          return `${f.message}${loc ? ' @ ' + (loc.file || '') + (loc.line ? ':' + loc.line : '') : ''}`;
        }),
      ],
      locations: findings.flatMap((f) => f.locations || []),
      recommendation,
      detail: findings.map((f) => ({
        type: f.evidence?.find((e) => e.startsWith('pattern:'))?.replace('pattern: ', '') || 'unknown',
        pattern: f.evidence?.find((e) => e.startsWith('pattern:'))?.replace('pattern: ', ''),
        confidence: f.confidenceScore,
        risk: f.confidenceScore,
        location: f.locations?.[0] || null,
      })),
    },
  ];
}
